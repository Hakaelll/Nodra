import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const messages = JSON.parse(
  readFileSync(resolve(root, "packages/shared/locales/en.json"), "utf8"),
);
const quote = (value) => JSON.stringify(value).replaceAll("$", "\\$");
for (const [source, translated] of Object.entries(messages)) {
  assert.equal(typeof translated, "string");
  assert.ok(source.trim() && translated.trim());
  assert.deepEqual(
    (source.match(/\{value\d+\}/g) ?? []).sort(),
    (translated.match(/\{value\d+\}/g) ?? []).sort(),
    source,
  );
}
const content =
  "// Generated by infrastructure/scripts/generate-locales.mjs.\n" +
  "const englishMessages = <String, String>{\n" +
  Object.entries(messages)
    .map(([source, translated]) => `  ${quote(source)}: ${quote(translated)},`)
    .join("\n") +
  "\n};\n";
writeFileSync(resolve(root, "apps/mobile/lib/l10n/messages_en.dart"), content);
console.log(
  `Generated ${Object.keys(messages).length} validated English messages for Flutter.`,
);
